st.markdown(
    """
### Research Objective

*Proactive School Meal Planning: Integrating Time Series Forecasting to Provide Decision
Support for Food Demand Prediction.* BiteTracker forecasts next-day/next-week school meal
demand so procurement and budgeting decisions can be made ahead of time, rather than
reacting to shortages or waste after the fact.

### Methodology

1. **Data pipeline** — schema validation, date parsing, chronological sorting, duplicate
   removal, per-school missing-value imputation, and per-school IQR outlier capping.
2. **Feature engineering** — lag (1/7/14-day) and rolling (7/14-day mean, 7-day std) meal
   counts, attendance rate, calendar/holiday/exam/event flags — all computed per school
   and strictly from past data to avoid leaking the future into training.
3. **Chronological train/test split** — last 20% of time-ordered rows held out; never
   shuffled.
4. **Baseline training** — four regressors trained with default hyperparameters to
   establish an honest starting point before any tuning.
5. **Hyperparameter tuning** — `GridSearchCV`/`RandomizedSearchCV` with `TimeSeriesSplit`
   (5 folds, chronological) on the training set only; the test set was never exposed
   during tuning.
6. **Model selection** — lowest test MAE as the primary criterion, RMSE as tiebreak, R² as
   supporting evidence, plus a generalization-gap check — not simply "highest R²".

### Models Compared

- Linear Regression (baseline)
- Decision Tree Regressor
- Random Forest Regressor
- XGBoost Regressor

### Technology Stack

Python 3, Pandas, NumPy, scikit-learn, XGBoost, Plotly, Streamlit, Joblib, Pytest.
PostgreSQL support is prepared in `config/settings.py` for future integration; the current
version uses CSV files.

### Ethical Considerations

- No student-level personally identifiable information is collected or required — no
  names, admission numbers, or phone numbers.
- Data is aggregated at the school-day level (enrolment, attendance counts, meal totals).
- Any future real dataset should use anonymized school identifiers, aggregated daily
  attendance/meal totals, secure storage, and comply with Kenya's **Data Protection Act,
  2019**.

### Synthetic Data Disclosure

**The dataset powering every chart, model, and forecast in this app is synthetic**,
generated by `src/synthetic_data.py` because a real dataset was not yet available at
build time. Relationships (e.g. rainfall depressing attendance, holidays halting service)
were hand-designed to be plausible, not fit to any real county's records. All measured
metrics (MAE/RMSE/R²) are genuine computations *on that synthetic data* — they validate
that the pipeline works correctly, not that the numbers will hold on real school data.
Swapping in a real dataset requires no code changes — only pointing
`config.settings.ACTIVE_DATA_PATH` at the new CSV (same column schema) and re-running the
pipeline end to end.

### Limitations

- Synthetic data only — no real-world performance claim is made.
- Multi-day forecasts feed each day's prediction back in as if observed, so errors can
  compound over longer horizons (see the Forecast page's disclosure).
- Weather/attendance for anything beyond "day 1" of a forecast falls back to a recent
  historical average, not a true forecast of those inputs.
- Only 3 synthetic schools across 2 academic years — a real deployment would need more
  schools and longer history for the models to generalize with confidence.

### Future Improvements

- Swap in real school-level data once available and re-run baseline + tuning from scratch.
- Add true weather/attendance forecasts as model inputs instead of historical-average
  fallbacks.
- Move from CSV to the prepared PostgreSQL schema for multi-user, real-time updates.
"""
)
