def make_stub_model(features: list[str] | None = None) -> LinearRegression:
    """A deterministic model built without fitting: 0.8 * lag_1 + 0.2 * rolling_mean_7 + 5."""
    features = list(FEATURE_COLUMNS if features is None else features)
    model = LinearRegression()
    weights = {"lag_1_meals": 0.8, "rolling_mean_7": 0.2}
    model.coef_ = np.array([weights.get(f, 0.0) for f in features])
    model.intercept_ = 5.0
    model.n_features_in_ = len(features)
    model.feature_names_in_ = np.array(features, dtype=object)
    return model


